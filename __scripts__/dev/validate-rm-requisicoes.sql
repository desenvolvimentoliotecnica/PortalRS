        R.RECMODIFIEDON
    FROM VREQAUMENTOQUADRO R
        WHERE (@Tipo IS NULL OR @Tipo = 'AUMENTO_QUADRO')
        AND (@DataDe IS NULL OR R.DATAABERTURA >= @DataDe)
        AND (@DataAte IS NULL OR R.DATAABERTURA < DATEADD(day, 1, @DataAte))
