-- Validação local da consulta admin requisições RM (espelha RmRequisicoesQueries.cs).
-- Parâmetros: mesmos defaults da tela (3 meses, status 1 e 3).
SET NOCOUNT ON;

DECLARE @Tipo NVARCHAR(80) = NULL;
DECLARE @DataDe DATE = '$(DataDe)';
DECLARE @DataAte DATE = '$(DataAte)';
DECLARE @CodStatusCsv VARCHAR(200) = ',1,3,';
DECLARE @SearchPattern NVARCHAR(4000) = NULL;
DECLARE @Offset INT = 0;
DECLARE @PageSize INT = 20;

PRINT '=== validate-rm-requisicoes ===';
PRINT CONCAT('Periodo: ', CONVERT(varchar(10), @DataDe, 120), ' .. ', CONVERT(varchar(10), @DataAte, 120));
PRINT CONCAT('CodStatusCsv: ', @CodStatusCsv);

