(
    SELECT
        'AUMENTO_QUADRO' AS TIPO_REQUISICAO,
        R.CODCOLREQUISICAO,
        R.IDREQ,
        R.JUSTIFICATIVA,
        R.DATAABERTURA,
        R.DATAPREVISTA,
        R.DATACONCLUSAO,
        R.DATACANCELAMENTO,
        R.CODSTATUS,
        R.CODCOLREQUISITANTE,
        R.CHAPAREQUISITANTE,
        R.CODATENDIMENTO,
        R.CODLOCAL,
        CAST(NULL AS VARCHAR(20)) AS TIPOREQPAI,
        CAST(NULL AS INT) AS IDREQPAI,
