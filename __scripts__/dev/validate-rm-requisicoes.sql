        CAST(NULL AS VARCHAR(30)),
        CAST(NULL AS INT),
        CAST(NULL AS VARCHAR(30)),
        CAST(NULL AS VARCHAR(30)),
        CAST(NULL AS VARCHAR(30)),
        CAST(NULL AS DECIMAL(18,2)),
        R.CODCCUSTO,
        R.RECCREATEDBY,
        R.RECCREATEDON,
        R.RECMODIFIEDBY,
        R.RECMODIFIEDON
