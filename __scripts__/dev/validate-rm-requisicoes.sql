    UNION ALL
    SELECT
        'SUBSTITUICAO',
        R.CODCOLREQUISICAO,
        R.IDREQ,
        R.JUSTIFICATIVA,
        R.DATAABERTURA,
        R.DATAPREVISTA,
        R.DATACONCLUSAO,
        R.DATACANCELAMENTO,
        R.CODSTATUS,
        R.CODCOLREQUISITANTE,
        R.CHAPAREQUISITANTE,
        R.CODATENDIMENTO,
        R.CODLOCAL,
        R.TIPOREQPAI,
        R.IDREQPAI,
        CAST(NULL AS VARCHAR(30)),
        R.CHAPASUBSTITUTO,
        CAST(NULL AS INT),
        R.CODFILIAL,
        R.CODSECAO,
        R.CODFUNCAO,
        R.VLRSALARIO,
        R.CODCCUSTO,
